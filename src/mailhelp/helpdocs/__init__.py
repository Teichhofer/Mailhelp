"""5.3 (H7): the packaged, reviewed help sections and the deterministic choice of context.

``sections.json`` and ``manifest.json`` are generated by ``python -m devtools.help_index`` from the
released documentation only. A missing, damaged or foreign resource (another application
version or revision) makes the help chat unavailable; settings and search keep working.
"""
from __future__ import annotations

import hashlib
import json
import re
from dataclasses import dataclass
from pathlib import Path

from .. import __version__

DIRECTORY = Path(__file__).resolve().parent
MAX_SECTIONS = 6
# Words that carry no meaning on their own; a match on them never selects a section.
STOPWORDS = frozenset(
    "aber alle als also auch auf aus bei bin bis das dass dem den der des die dies diese dieser doch ein eine "
    "einem einen einer es fuer gibt habe hat ich ihr im in ist ja kann man mich mir mit muss nach nicht noch "
    "nur oder sich sie sind so soll und uns von vor wann warum was weil wenn wer wie wird wo zu zum zur "
    "mailhelp bitte genau unterschied zwischen bedeutet macht".split())


class HelpUnavailable(Exception):
    """The packaged help resource is missing, damaged or does not belong to this version."""


@dataclass(frozen=True)
class Section:
    id: str
    title: str
    path: tuple[str, ...]
    source: str
    text: str
    setting_ids: tuple[str, ...]

    @property
    def size(self) -> int:
        return len(self.text.encode("utf-8"))


def words(text: str) -> list[str]:
    from ..web.settings_search import normalize
    return [word for word in re.findall(r"[a-z0-9_.]+", normalize(text)) if len(word) > 2 and word not in STOPWORDS]


def _expanded(terms: list[str]) -> set[str]:
    from ..web.settings_search import SYNONYMS, normalize
    found = set(terms)
    for group in SYNONYMS:
        folded = {normalize(item) for item in group}
        if found & folded:
            found |= {word for item in folded for word in item.split()}
    return found


def _settings_named(asked: set[str]) -> set[str]:
    """Settings a question names by their key or a long word of their label, e.g. "Abrufintervall"."""
    from ..web.settings_search import catalog, normalize
    labels = {entry.key: {word for word in re.findall(r"[a-z0-9]+", normalize(entry.label)) if len(word) >= 6}
              for entry in catalog() if entry.key is not None}
    # Only words that name at most two settings are specific ("Abrufintervall", not "Postfach").
    counts: dict[str, int] = {}
    for label in labels.values():
        for word in label:
            counts[word] = counts.get(word, 0) + 1
    return {key for key, label in labels.items()
            if normalize(key) in asked or {word for word in asked & label if counts[word] <= 2}}


@dataclass(frozen=True)
class HelpBase:
    revision: str
    sections: tuple[Section, ...]

    def get(self, section_id: str) -> Section | None:
        return next((section for section in self.sections if section.id == section_id), None)

    def select(self, question: str, *, setting_id: str | None = None, history: tuple[str, ...] = (),
               limit: int = MAX_SECTIONS, budget: int = 24000) -> list[Section]:
        """At most *limit* relevant sections within *budget* bytes, best first; never a guess.

        A section counts only if it names the referenced setting, or if at least two different
        meaningful words of the question (or one word of a short question in its title) occur in it.
        Earlier questions add their words with lower weight for follow-up questions.
        """
        asked = _expanded(words(question))
        earlier = _expanded([word for text in history for word in words(text)]) - asked
        # A follow-up such as "Und pro Postfach?" keeps the settings of the earlier questions.
        referenced = _settings_named(asked | earlier) | ({setting_id} if setting_id else set())
        scored = []
        for section in self.sections:
            title = set(words(" ".join(section.path)))
            body = set(words(section.text))
            matched = {word for word in asked if word in title or word in body}
            score = 3 * len(asked & title) + len(matched) + len(earlier & title)
            named = bool(referenced & set(section.setting_ids))
            strong = named or len(matched) >= 2 or (len(asked) <= 2 and bool(asked & title))
            if strong:
                scored.append((-(score + (10 if named else 0)), section.id, section))
        chosen: list[Section] = []
        used = 0
        for _rank, _identity, section in sorted(scored):
            if len(chosen) == limit:
                break
            if used + section.size <= budget:
                chosen.append(section)
                used += section.size
        return chosen


def load(directory: Path = DIRECTORY, version: str = __version__) -> HelpBase:
    try:
        manifest = json.loads((directory / "manifest.json").read_text(encoding="utf-8"))
        payload = (directory / "sections.json").read_text(encoding="utf-8").rstrip("\n")
        raw = json.loads(payload)
    except (OSError, ValueError) as exc:
        raise HelpUnavailable("Hilfebestand fehlt oder ist beschädigt") from exc
    if not isinstance(manifest, dict) or manifest.get("schema_version") != 1 or manifest.get("app_version") != version:
        raise HelpUnavailable("Hilfebestand gehört zu einer anderen Version")
    if manifest.get("revision") != hashlib.sha256(payload.encode("utf-8")).hexdigest():
        raise HelpUnavailable("Hilfebestand passt nicht zu seinem Manifest")
    try:
        sections = tuple(Section(id=item["id"], title=item["title"], path=tuple(item["path"]), source=item["source"],
                                 text=item["text"], setting_ids=tuple(item["setting_ids"])) for item in raw)
    except (KeyError, TypeError) as exc:
        raise HelpUnavailable("Hilfebestand hat einen unbekannten Aufbau") from exc
    return HelpBase(manifest["revision"], sections)
