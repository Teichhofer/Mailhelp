"""5.3 (H7): the packaged, reviewed help sections and the deterministic choice of context.

``sections.json`` and ``manifest.json`` are generated by ``python -m devtools.help_index`` from the
released documentation only. A missing, damaged or foreign resource (another application
version or revision) makes the help chat unavailable; settings and search keep working.
"""
from __future__ import annotations

import hashlib
import json
import re
from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from pydantic import BaseModel, ConfigDict, Field

from .. import __version__

DIRECTORY = Path(__file__).resolve().parent
MAX_SECTIONS = 6
STEM = 5
# A word of at least this length that occurs in at most three sections carries a topic on its own.
RARE_LENGTH, RARE_SECTIONS = 8, 3
# Words that carry no meaning on their own; a match on them never selects a section.
STOPWORDS = frozenset(
    "aber alle als also auch auf aus bei bin bis das dass dem den der des die dies diese dieser doch ein eine "
    "einem einen einer es fuer gibt habe hat ich ihr im in ist ja kann man mich mir mit muss nach nicht noch "
    "nur oder sich sie sind so soll und uns von vor wann warum was weil wenn wer wie wird wo zu zum zur "
    "mailhelp bitte genau unterschied zwischen bedeutet macht mein meine meinen meiner dein deine einer einen "
    "einem eines dann denn".split())


class HelpAnswer(BaseModel):
    """5.3 (H8): the structured answer of the ``settings_help`` step."""

    model_config = ConfigDict(extra="forbid", strict=True)
    answer: str = Field(min_length=1, max_length=4000)
    # 5.5.4: the core statement for the small window, written in the same call (no extra cost).
    short_answer: str = Field(default="", max_length=1000)
    source_ids: list[str] = Field(default_factory=list, max_length=MAX_SECTIONS)
    setting_ids: list[str] = Field(default_factory=list, max_length=10)
    needs_clarification: bool = False


SHORT_ANSWER = 300
# A sentence ends at . ! ? before a space or the end, but not after a digit ("1.", "3. Mai").
_SENTENCE_END = re.compile(r"(?<![0-9])[.!?](?=\s|$)")


def derive_short_answer(text: str, limit: int = SHORT_ANSWER) -> str:
    """The first sentence of at least 20 characters, shortened at a word to ``limit``.

    Used when a model (or an answer from before 5.5.4) gives no usable short answer. Markdown
    marks are removed first (5.5.6), so a cut never leaves a dangling ``**``.
    """
    from .markdown import plain
    text = " ".join(plain(text).split())
    end = next((match.end() for match in _SENTENCE_END.finditer(text) if match.end() >= 20), len(text))
    first = text[:end]
    if len(first) <= limit:
        return first
    return first[:limit - 1].rsplit(" ", 1)[0].rstrip(",;:") + "…"


def concise(answer: str, short_answer: str) -> str:
    """What the window shows first: the model's short answer if it is short, else derived.

    The length counts the visible text; a short answer may keep its inline Markdown.
    """
    from .markdown import plain
    short = " ".join(short_answer.split())
    if short and len(" ".join(plain(short).split())) <= SHORT_ANSWER:
        return short
    return derive_short_answer(short or answer)


def same_text(first: str, second: str) -> bool:
    """Whether two answers read the same once Markdown marks and spacing are ignored."""
    from .markdown import plain
    return " ".join(plain(first).split()) == " ".join(plain(second).split())


def answer_validator(sources: list[str], settings: list[str]) -> Callable[[Any], HelpAnswer]:
    """Only sources that were sent and settings from the catalog; anything else is a schema error."""
    def validate(value: Any) -> HelpAnswer:
        answer = HelpAnswer.model_validate(value)
        if set(answer.source_ids) - set(sources) or set(answer.setting_ids) - set(settings):
            raise ValueError("Unbekannte Quellen- oder Einstellungskennung")
        return answer
    return validate


class HelpUnavailable(Exception):
    """The packaged help resource is missing, damaged or does not belong to this version."""


@dataclass(frozen=True)
class Section:
    id: str
    title: str
    path: tuple[str, ...]
    source: str
    text: str
    setting_ids: tuple[str, ...]

    @property
    def size(self) -> int:
        return len(self.text.encode("utf-8"))


def stems(text: str) -> list[str]:
    """Meaningful words shortened to five letters, so inflected forms meet ("starte", "starten")."""
    return [word[:STEM] for word in words(text)]


def words(text: str) -> list[str]:
    from ..web.settings_search import normalize
    return [word for word in re.findall(r"[a-z0-9_.]+", normalize(text)) if len(word) > 2 and word not in STOPWORDS]


def _expanded(terms: set[str]) -> set[str]:
    """The stems of the question with the stems of their synonyms."""
    from ..web.settings_search import SYNONYMS, normalize
    found = set(terms)
    for group in SYNONYMS:
        folded = {word[:STEM] for item in group for word in normalize(item).split()}
        if found & folded:
            found |= folded
    return found


def _settings_named(asked: set[str]) -> set[str]:
    """Settings a question names by their key or a long word of their label, e.g. "Abrufintervall"."""
    from ..web.settings_search import catalog, normalize
    labels = {entry.key: {word for word in re.findall(r"[a-z0-9]+", normalize(entry.label)) if len(word) >= 6}
              for entry in catalog() if entry.key is not None}
    # Only words that name at most two settings are specific ("Abrufintervall", not "Postfach").
    counts: dict[str, int] = {}
    for label in labels.values():
        for word in label:
            counts[word] = counts.get(word, 0) + 1
    return {key for key, label in labels.items()
            if normalize(key) in asked or {word for word in asked & label if counts[word] <= 2}}


@dataclass(frozen=True)
class HelpBase:
    revision: str
    sections: tuple[Section, ...]

    def get(self, section_id: str) -> Section | None:
        return next((section for section in self.sections if section.id == section_id), None)

    def select(self, question: str, *, setting_id: str | None = None, history: tuple[str, ...] = (),
               limit: int = MAX_SECTIONS, budget: int = 24000) -> list[Section]:
        """At most *limit* relevant sections within *budget* bytes, best first; never a guess.

        A section counts if it names a referenced setting, if two different words of the question
        (or one word and a synonym) occur in it, if a rare word of the question (in at most three
        sections) occurs in it, or if a word of a short question is in its title. Words are compared
        by a short stem, so "starte" finds "starten". Earlier questions help follow-up questions.
        """
        own = set(stems(question))
        specific = {word[:STEM] for word in words(question) if len(word) >= RARE_LENGTH}
        asked = _expanded(own)
        earlier = _expanded({word for text in history for word in stems(text)}) - asked
        referenced = _settings_named(set(words(question))) | ({setting_id} if setting_id else set())
        # A follow-up such as "Und pro Postfach?" keeps the settings of the earlier questions,
        # but only where the new question fits as well (or has no meaningful word of its own).
        remembered = _settings_named({word for text in history for word in words(text)})
        frequency = self._frequency()
        scored = []
        for section in self.sections:
            title, body = self._index[section.id]
            hits = {word for word in own if word in title or word in body}
            synonym = bool((asked - own) & (title | body))
            score = 3 * len(asked & title) + len(hits) + int(synonym) + len(earlier & title)
            heading = set(stems(section.title))
            score += 6 * len(asked & heading) // max(1, len(heading))
            named = bool(referenced & set(section.setting_ids)) or (
                bool(remembered & set(section.setting_ids)) and (bool(hits) or not own))
            rare = any(frequency[word] <= RARE_SECTIONS for word in hits & specific)
            strong = (named or len(hits) >= 2 or (bool(hits) and synonym) or rare
                      or (len(own) <= 2 and bool(asked & title)))
            if strong:
                scored.append((-(score + (10 if named else 0)), section.id, section))
        chosen: list[Section] = []
        used = 0
        for _rank, _identity, section in sorted(scored):
            if len(chosen) == limit:
                break
            if used + section.size <= budget:
                chosen.append(section)
                used += section.size
        return chosen

    @property
    def _index(self) -> dict[str, tuple[set[str], set[str]]]:
        cached = self.__dict__.get("_cached_index")
        if cached is None:
            cached = {section.id: (set(stems(" ".join(section.path))), set(stems(section.text)))
                      for section in self.sections}
            object.__setattr__(self, "_cached_index", cached)
        return cached

    def _frequency(self) -> dict[str, int]:
        """In how many sections each stem occurs; rare stems carry a topic on their own."""
        counts: dict[str, int] = {}
        for title, body in self._index.values():
            for word in title | body:
                counts[word] = counts.get(word, 0) + 1
        return counts


def load(directory: Path = DIRECTORY, version: str = __version__) -> HelpBase:
    try:
        manifest = json.loads((directory / "manifest.json").read_text(encoding="utf-8"))
        payload = (directory / "sections.json").read_text(encoding="utf-8").rstrip("\n")
        raw = json.loads(payload)
    except (OSError, ValueError) as exc:
        raise HelpUnavailable("Hilfebestand fehlt oder ist beschädigt") from exc
    if not isinstance(manifest, dict) or manifest.get("schema_version") != 1 or manifest.get("app_version") != version:
        raise HelpUnavailable("Hilfebestand gehört zu einer anderen Version")
    if manifest.get("revision") != hashlib.sha256(payload.encode("utf-8")).hexdigest():
        raise HelpUnavailable("Hilfebestand passt nicht zu seinem Manifest")
    try:
        sections = tuple(Section(id=item["id"], title=item["title"], path=tuple(item["path"]), source=item["source"],
                                 text=item["text"], setting_ids=tuple(item["setting_ids"])) for item in raw)
    except (KeyError, TypeError) as exc:
        raise HelpUnavailable("Hilfebestand hat einen unbekannten Aufbau") from exc
    return HelpBase(manifest["revision"], sections)
